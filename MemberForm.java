    private void tblMembersMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblMembersMouseClicked
    int selectedRow = tblMembers.getSelectedRow();

if (selectedRow != -1) {

    txtMemberName.setText(
            tblMembers.getValueAt(selectedRow, 1).toString()
    );

    txtEmail.setText(
            tblMembers.getValueAt(selectedRow, 2).toString()
    );

    cmbRole.setSelectedItem(
            tblMembers.getValueAt(selectedRow, 3).toString()
    );
}
    }//GEN-LAST:event_tblMembersMouseClicked

