    private void btnAddMemberActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddMemberActionPerformed
    
    String memberName = txtMemberName.getText().trim();
    String email = txtEmail.getText().trim();
    String role = cmbRole.getSelectedItem().toString();

    if (memberName.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please enter the member name."
        );
        return;
    }

    model.Member member = new model.Member(
            0,
            memberName,
            email,
            role
    );

    dao.MemberDAO memberDAO = new dao.MemberDAO();

    if (memberDAO.addMember(member)) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Member added successfully!"
        );

        loadMembers();

        txtMemberName.setText("");
        txtEmail.setText("");
        cmbRole.setSelectedIndex(0);

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Failed to add member."
        );
    }

    }//GEN-LAST:event_btnAddMemberActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
    
    int selectedRow = tblMembers.getSelectedRow();

    if (selectedRow == -1) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please select a member first."
        );
        return;
    }

    int memberId = Integer.parseInt(
            tblMembers.getValueAt(selectedRow, 0).toString()
    );

    String memberName = txtMemberName.getText().trim();
    String email = txtEmail.getText().trim();
    String role = cmbRole.getSelectedItem().toString();

    if (memberName.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please enter the member name."
        );
        return;
    }

    model.Member member = new model.Member(
            memberId,
            memberName,
            email,
            role
    );

    dao.MemberDAO memberDAO = new dao.MemberDAO();

    if (memberDAO.updateMember(member)) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Member updated successfully!"
        );

        loadMembers();

        txtMemberName.setText("");
        txtEmail.setText("");
        cmbRole.setSelectedIndex(0);

        tblMembers.clearSelection();

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Failed to update member."
        );
    }

    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
    
    int selectedRow = tblMembers.getSelectedRow();

    if (selectedRow == -1) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please select a member first."
        );
        return;
    }

    int memberId = Integer.parseInt(
            tblMembers.getValueAt(selectedRow, 0).toString()
    );

    int confirm = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this member?",
            "Confirm Delete",
            javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (confirm == javax.swing.JOptionPane.YES_OPTION) {

        dao.MemberDAO memberDAO = new dao.MemberDAO();

        if (memberDAO.deleteMember(memberId)) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Member deleted successfully!"
            );

            loadMembers();

            txtMemberName.setText("");
            txtEmail.setText("");
            cmbRole.setSelectedIndex(0);

            tblMembers.clearSelection();

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Failed to delete member."
            );
        }
    }

    }//GEN-LAST:event_btnDeleteActionPerformed

