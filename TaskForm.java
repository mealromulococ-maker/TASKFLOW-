    private void btnAddTaskActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddTaskActionPerformed
       
    try {

        String taskName = txtTaskName.getText().trim();
        String description = txtDescription.getText().trim();
        String deadlineText = txtDeadline.getText().trim();

        // Check required fields
        if (taskName.isEmpty()
                || deadlineText.isEmpty()
                || cmbProject.getSelectedItem() == null
                || cmbAssignedTo.getSelectedItem() == null) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please fill in all required fields."
            );
            return;
        }

        // Get Project ID
        String projectText =
                cmbProject.getSelectedItem().toString();

        int projectId = Integer.parseInt(
                projectText.split(" - ")[0]
        );

        // Get Member ID
        String memberText =
                cmbAssignedTo.getSelectedItem().toString();

        int assignedTo = Integer.parseInt(
                memberText.split(" - ")[0]
        );

        // Get Priority and Status
        String priority =
                cmbPriority.getSelectedItem().toString();

        String status =
                cmbStatus.getSelectedItem().toString();

        // Convert deadline to LocalDate
        java.time.LocalDate deadline =
                java.time.LocalDate.parse(deadlineText);

        // Create Task object
        model.Task task = new model.Task(
                0,
                projectId,
                taskName,
                description,
                assignedTo,
                priority,
                deadline,
                status
        );

        // Save to database
        dao.TaskDAO taskDAO = new dao.TaskDAO();

        if (taskDAO.addTask(task)) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Task added successfully!"
    );

    loadTasks();

    // Clear fields
            txtTaskName.setText("");
            txtDescription.setText("");
            txtDeadline.setText("");

            cmbPriority.setSelectedIndex(0);
            cmbStatus.setSelectedIndex(0);

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Failed to add task."
            );
        }

    } catch (java.time.format.DateTimeParseException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Invalid deadline format. Please use YYYY-MM-DD."
        );

    }


    }//GEN-LAST:event_btnAddTaskActionPerformed

    private void tblTasksMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblTasksMouseClicked
        int selectedRow = tblTasks.getSelectedRow();

if (selectedRow != -1) {

    // Task Name
    txtTaskName.setText(
            tblTasks.getValueAt(selectedRow, 1).toString()
    );

    // Project
    String projectId =
            tblTasks.getValueAt(selectedRow, 2).toString();

    for (int i = 0; i < cmbProject.getItemCount(); i++) {

        if (cmbProject.getItemAt(i).startsWith(projectId + " - ")) {
            cmbProject.setSelectedIndex(i);
            break;
        }
    }

    // Assigned To
    String memberId =
            tblTasks.getValueAt(selectedRow, 3).toString();

    for (int i = 0; i < cmbAssignedTo.getItemCount(); i++) {

        if (cmbAssignedTo.getItemAt(i).startsWith(memberId + " - ")) {
            cmbAssignedTo.setSelectedIndex(i);
            break;
        }
    }

    // Priority
    cmbPriority.setSelectedItem(
            tblTasks.getValueAt(selectedRow, 4).toString()
    );

    // Deadline
    txtDeadline.setText(
            tblTasks.getValueAt(selectedRow, 5).toString()
    );

    // Status
    cmbStatus.setSelectedItem(
            tblTasks.getValueAt(selectedRow, 6).toString()
    );
}
    }//GEN-LAST:event_tblTasksMouseClicked

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
       int selectedRow = tblTasks.getSelectedRow();

if (selectedRow == -1) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select a task first."
    );

    return;
}

try {

    // Get Task ID from selected row
    int taskId = Integer.parseInt(
            tblTasks.getValueAt(selectedRow, 0).toString()
    );

    // Get values from form
    String taskName = txtTaskName.getText().trim();
    String description = txtDescription.getText().trim();
    String deadlineText = txtDeadline.getText().trim();

    if (taskName.isEmpty() || deadlineText.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please fill in the required fields."
        );

        return;
    }

    // Get Project ID
    String projectText =
            cmbProject.getSelectedItem().toString();

    int projectId = Integer.parseInt(
            projectText.split(" - ")[0]
    );

    // Get Member ID
    String memberText =
            cmbAssignedTo.getSelectedItem().toString();

    int assignedTo = Integer.parseInt(
            memberText.split(" - ")[0]
    );

    // Get Priority and Status
    String priority =
            cmbPriority.getSelectedItem().toString();

    String status =
            cmbStatus.getSelectedItem().toString();

    // Convert deadline
    java.time.LocalDate deadline =
            java.time.LocalDate.parse(deadlineText);

    // Create updated Task object
    model.Task task = new model.Task(
            taskId,
            projectId,
            taskName,
            description,
            assignedTo,
            priority,
            deadline,
            status
    );

    // Update database
    dao.TaskDAO taskDAO = new dao.TaskDAO();

    if (taskDAO.updateTask(task)) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Task updated successfully!"
        );

        // Refresh table
        loadTasks();

        // Clear fields
        txtTaskName.setText("");
        txtDescription.setText("");
        txtDeadline.setText("");

        cmbPriority.setSelectedIndex(0);
        cmbStatus.setSelectedIndex(0);

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Failed to update task."
        );
    }

} catch (java.time.format.DateTimeParseException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Invalid deadline format. Please use YYYY-MM-DD."
    );

}
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        int selectedRow = tblTasks.getSelectedRow();

if (selectedRow == -1) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select a task first."
    );

    return;
}

int taskId = Integer.parseInt(
        tblTasks.getValueAt(selectedRow, 0).toString()
);

int confirm = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete this task?",
        "Confirm Delete",
        javax.swing.JOptionPane.YES_NO_OPTION
);

if (confirm == javax.swing.JOptionPane.YES_OPTION) {

    dao.TaskDAO taskDAO = new dao.TaskDAO();

    if (taskDAO.deleteTask(taskId)) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Task deleted successfully!"
        );

        loadTasks();

        txtTaskName.setText("");
        txtDescription.setText("");
        txtDeadline.setText("");

        cmbPriority.setSelectedIndex(0);
        cmbStatus.setSelectedIndex(0);

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Failed to delete task."
        );
    }
}
    }//GEN-LAST:event_btnDeleteActionPerformed

