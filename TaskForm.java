    private void loadProjects() {
    cmbProject.removeAllItems();

    dao.ProjectDAO projectDAO = new dao.ProjectDAO();

    java.util.List<model.Project> projects =
            projectDAO.getAllProjects();

    for (model.Project project : projects) {
        cmbProject.addItem(
                project.getProjectId() + " - " +
                project.getProjectName()
        );
    }
}
    private void loadMembers() {
    cmbAssignedTo.removeAllItems();

    dao.MemberDAO memberDAO = new dao.MemberDAO();

    java.util.List<model.Member> members =
            memberDAO.getAllMembers();

    for (model.Member member : members) {
        cmbAssignedTo.addItem(
                member.getMemberId() + " - " +
                member.getMemberName()
        );
    }
}
    private void loadTasks() {

    dao.TaskDAO taskDAO = new dao.TaskDAO();

    java.util.List<model.Task> tasks =
            taskDAO.getAllTasks();

    javax.swing.table.DefaultTableModel tableModel =
            (javax.swing.table.DefaultTableModel) tblTasks.getModel();

    tableModel.setRowCount(0);

    for (model.Task task : tasks) {

        tableModel.addRow(new Object[]{
            task.getTaskId(),
            task.getTaskName(),
            task.getProjectId(),
            task.getAssignedTo(),
            task.getPriority(),
            task.getDeadline(),
            task.getStatus()
        });
    }
}
