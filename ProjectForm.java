    private void loadProjects() {

    dao.ProjectDAO projectDAO = new dao.ProjectDAO();

    java.util.List<model.Project> projects =
            projectDAO.getAllProjects();

    javax.swing.table.DefaultTableModel tableModel =
            (javax.swing.table.DefaultTableModel) tblProjects.getModel();

    tableModel.setRowCount(0);

    for (model.Project project : projects) {

        tableModel.addRow(new Object[]{
            project.getProjectId(),
            project.getProjectName(),
            project.getDescription(),
            project.getStartDate(),
            project.getDeadline(),
            project.getStatus()
        });
    }
}
    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
      
  
    int selectedRow = tblProjects.getSelectedRow();

    if (selectedRow == -1) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please select a project first."
        );
        return;
    }

    try {

        int projectId = Integer.parseInt(
                tblProjects.getValueAt(selectedRow, 0).toString()
        );

        String projectName = txtProjectName.getText();
        String description = txtDescription.getText();
        String startDateText = txtStartDate.getText();
        String deadlineText = txtDeadline.getText();
        String status = cmbStatus.getSelectedItem().toString();

        if (projectName.trim().isEmpty()
                || startDateText.trim().isEmpty()
                || deadlineText.trim().isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please fill in the required fields."
            );
            return;
        }

        java.time.LocalDate startDate =
                java.time.LocalDate.parse(startDateText);

        java.time.LocalDate deadline =
                java.time.LocalDate.parse(deadlineText);

        model.Project project = new model.Project(
                projectId,
                projectName,
                description,
                startDate,
                deadline,
                status,
                1
        );

        dao.ProjectDAO projectDAO = new dao.ProjectDAO();

        if (projectDAO.updateProject(project)) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Project updated successfully!"
            );

            loadProjects();

            txtProjectName.setText("");
            txtDescription.setText("");
            txtStartDate.setText("");
            txtDeadline.setText("");
            cmbStatus.setSelectedIndex(0);

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Failed to update project."
            );
        }

    } catch (java.time.format.DateTimeParseException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Invalid date format. Please use YYYY-MM-DD."
        );
    }

    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnAddProjectActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddProjectActionPerformed

    try {
        String projectName = txtProjectName.getText();
        String description = txtDescription.getText();
        String startDateText = txtStartDate.getText();
        String deadlineText = txtDeadline.getText();
        String status = cmbStatus.getSelectedItem().toString();

        // Check required fields
        if (projectName.isEmpty() ||
            startDateText.isEmpty() ||
            deadlineText.isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please fill in the required fields."
            );
            return;
        }

        // Convert text dates to LocalDate
        java.time.LocalDate startDate =
                java.time.LocalDate.parse(startDateText);

        java.time.LocalDate deadline =
                java.time.LocalDate.parse(deadlineText);

        // Create Project object
        model.Project project = new model.Project(
                0,
                projectName,
                description,
                startDate,
                deadline,
                status,
                1
        );

        // Save project to database
        dao.ProjectDAO projectDAO = new dao.ProjectDAO();

        if (projectDAO.addProject(project)) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Project added successfully!"
            );
            
            loadProjects();

            // Clear fields
            txtProjectName.setText("");
            txtDescription.setText("");
            txtStartDate.setText("");
            txtDeadline.setText("");
            cmbStatus.setSelectedIndex(0);

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Failed to add project."
            );
        }

    } catch (java.time.format.DateTimeParseException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Invalid date format.\nPlease use YYYY-MM-DD.\nExample: 2026-09-09"
        );
    }

    }//GEN-LAST:event_btnAddProjectActionPerformed

